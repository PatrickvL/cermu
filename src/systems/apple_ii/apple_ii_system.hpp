/*
 * apple_ii_system.h — Apple II family system declaration
 *
 * Apple II (1977), Apple IIe (1983), Apple IIc (1984).
 * All are 6502/65C02-based with soft-switch video generation.
 *
 * Apple II:
 *   - MOS 6502 @ 1.023 MHz
 *   - 48KB RAM (max), 12KB ROM (Integer/Applesoft BASIC + Monitor)
 *   - 40×24 text, 280×192 hi-res, 40×48 lo-res — all soft-switch controlled
 *   - 1-bit speaker toggle, no sound chip
 *   - 8 expansion slots
 *
 * Apple IIe:
 *   - WDC 65C02 @ 1.023 MHz
 *   - 128KB RAM (64KB + 64KB auxiliary), 16KB ROM
 *   - 80-column text, double hi-res (560×192)
 *   - Same 1-bit speaker, same soft-switch video
 *
 * Apple IIc:
 *   - WDC 65C02 @ 1.023 MHz
 *   - 128KB RAM, 32KB ROM
 *   - Same display modes as IIe
 *   - Built-in 5.25" floppy, serial ports
 *
 * Memory map (48K Apple II):
 *   $0000–$BFFF : 48KB RAM (zero page, stack, text/hires pages)
 *   $C000–$C0FF : Soft switches (keyboard, speaker, display mode, I/O)
 *   $C100–$C7FF : Expansion slot I/O space (7 slots × 256 bytes)
 *   $C800–$CFFF : Shared expansion ROM space
 *   $D000–$FFFF : ROM (BASIC + Monitor)
 */

