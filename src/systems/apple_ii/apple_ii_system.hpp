// ============================================================================
// Apple II System
// ============================================================================

template<AppleIIVariant V>
class AppleIISystem : public System {
    using Traits = AppleIIVariantTraits<V>;
    using BTraits = AppleIIBusTraits<V>;

public:
    AppleIISystem();
    ~AppleIISystem() override;

    // ── System interface ─────────────────────────────────────────
    const SystemDescriptor& get_descriptor() const override;
    bool set_configuration(const SystemConfiguration& config) override;
    bool apply_configuration() override;

    bool initialize() override;
    void shutdown() override;
    void reset() override;

    void tick() override;
    void run_frame() override;

    bool load_file(const char* filepath) override;

    uint32_t get_audio_samples(float* buffer, uint32_t max_samples) override;
    void set_audio_sample_rate(int sample_rate_hz) override;

    void handle_keyboard_event(SDL_Keycode key, bool pressed) override;
    void handle_text_input(const char* text) override;

    void* get_video_port_ptr() override { return video_port_.get(); }

private:
    // ── Chips (value-typed via Board Chips) ────────────────────────────

    // ── Memory chips — post-init pointers ────────────────────────────────
    ROMChip* rom_       = nullptr;
    uint8_t* ram_ptr_   = nullptr;   // Direct pointer for soft-switch video rendering

    // ── Board + bus ──────────────────────────────────────────────────────
    using Bus       = MemoryBus<typename BTraits::Spec>;
    using MainBoard = AppleIIBoard<V>;
    Bus       bus_;
    MainBoard board_{BTraits::kManifest};

    // ── Display ──────────────────────────────────────────────────────────
    uint8_t pixel_buffer_[apple_ii_constants::DISPLAY_WIDTH * apple_ii_constants::DISPLAY_HEIGHT] = {};
    std::unique_ptr<CompositeVideoPort> video_port_;

    // ── Soft switch state ────────────────────────────────────────────────
    bool    sw_text_     = true;     // Text/Graphics mode
    bool    sw_mixed_    = false;    // Mixed text+graphics
    bool    sw_page2_    = false;    // Display page select
    bool    sw_hires_    = false;    // Hi-res / Lo-res
    bool    sw_80col_    = false;    // 80-column mode (IIe/IIc only)
    bool    sw_altchar_  = false;    // Alternate character set (IIe/IIc only)

    // ── Memory banking (IIe/IIc) ────────────────────────────────────────
    bool    sw_auxmem_   = false;    // Auxiliary memory read
    bool    sw_auxwrite_ = false;    // Auxiliary memory write
    bool    sw_lcram_    = false;    // Language card RAM enable
    bool    sw_lcwrite_  = false;    // Language card write enable
    bool    sw_lcbank2_  = false;    // Language card bank 2 select

    // ── Keyboard ─────────────────────────────────────────────────────────
    uint8_t kbd_data_    = 0;        // Last key, bit 7 = strobe
    bool    kbd_strobe_  = false;

    // ── Speaker ──────────────────────────────────────────────────────────
    bool    spkr_state_  = false;    // Current speaker level
    int     audio_sample_rate_ = apple_ii_constants::DEFAULT_SAMPLE_RATE;

    // ── System state ─────────────────────────────────────────────────────
    bus_state_t pins_      = APPLE_II_BUS_DEFAULT_STATE;

    // ── Internal helpers ─────────────────────────────────────────────────
    void configure_bus_memory_map();
    void render_frame();
    bool load_roms();
    uint8_t soft_switch_read(uint16_t addr);
    void    soft_switch_write(uint16_t addr, uint8_t data);
};
