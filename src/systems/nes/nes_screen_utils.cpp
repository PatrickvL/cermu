// ============================================================================
// FONT UPLOAD
// ============================================================================

void nes_screen_init_font(PPU* ppu) {
    if (!ppu) return;

    // Upload font glyphs into CHR-RAM pattern table 0.
    // Each NES tile is 16 bytes: 8 bytes plane 0 (lo bits) + 8 bytes plane 1 (hi bits).
    // For a 1-colour font, plane 0 = glyph data, plane 1 = all zeros.
    // This gives pixel values of 0 (transparent/bg) or 1 (fg colour from palette).
    //
    // Tile address = tile_index * 16.
    // We place ASCII 0x20-0x7F at tile indices 0x20-0x7F.

    for (int ch = 0x20; ch <= 0x7F; ch++) {
        uint16_t tile_addr = static_cast<uint16_t>(ch * 16);
        const uint8_t* glyph = ascii_font_8x8[ch - 0x20];

        for (int row = 0; row < 8; row++) {
            // Plane 0 (low bits) = glyph row
            ppu->ppu_write(tile_addr + row, glyph[row]);
            // Plane 1 (high bits) = 0 (single colour)
            ppu->ppu_write(tile_addr + row + 8, 0x00);
        }
    }

    // Also create a solid block at tile 0x01 (for horizontal bars)
    for (int row = 0; row < 8; row++) {
        ppu->ppu_write(0x0010 + row, 0xFF);       // Plane 0: all pixels set
        ppu->ppu_write(0x0010 + row + 8, 0x00);   // Plane 1: zero
    }

    printf("NES: Uploaded 8x8 ASCII font to CHR-RAM (tiles 0x20-0x7F)\n");
}

// ============================================================================
// PALETTE SETUP
// ============================================================================

void nes_screen_set_palette(PPU* ppu,
                            uint8_t bg_color,
                            uint8_t fg_color,
                            uint8_t accent_color,
                            uint8_t dim_color) {
    if (!ppu) return;

    // Background palette 0: bg_color, fg_color, accent_color, dim_color
    ppu->ppu_write(0x3F00, bg_color);      // Universal background
    ppu->ppu_write(0x3F01, fg_color);      // Palette 0, colour 1 (text)
    ppu->ppu_write(0x3F02, accent_color);  // Palette 0, colour 2 (accent)
    ppu->ppu_write(0x3F03, dim_color);     // Palette 0, colour 3 (dim)

    // Background palette 1: same bg, accent as fg (for headers/bars)
    ppu->ppu_write(0x3F04, bg_color);
    ppu->ppu_write(0x3F05, accent_color);  // Palette 1, colour 1
    ppu->ppu_write(0x3F06, fg_color);      // Palette 1, colour 2
    ppu->ppu_write(0x3F07, dim_color);     // Palette 1, colour 3

    // Background palette 2: same bg, dim as fg (for labels/dimmed text)
    ppu->ppu_write(0x3F08, bg_color);
    ppu->ppu_write(0x3F09, dim_color);     // Palette 2, colour 1
    ppu->ppu_write(0x3F0A, fg_color);      // Palette 2, colour 2
    ppu->ppu_write(0x3F0B, accent_color);  // Palette 2, colour 3

    // Background palette 3: highlight (for "NOW PLAYING" etc.)
    ppu->ppu_write(0x3F0C, bg_color);
    ppu->ppu_write(0x3F0D, 0x16);         // Red-ish accent
    ppu->ppu_write(0x3F0E, fg_color);
    ppu->ppu_write(0x3F0F, accent_color);
}

// ============================================================================
// SCREEN CLEAR
// ============================================================================

void nes_screen_clear(PPU* ppu) {
    if (!ppu) return;

    // Fill nametable 0 ($2000-$23BF) with space tiles (0x20)
    for (uint16_t addr = 0x2000; addr < 0x23C0; addr++) {
        ppu->ppu_write(addr, 0x20);  // Space tile
    }

    // Clear attribute table ($23C0-$23FF) to palette 0
    for (uint16_t addr = 0x23C0; addr <= 0x23FF; addr++) {
        ppu->ppu_write(addr, 0x00);
    }
}

// ============================================================================
// TEXT RENDERING
// ============================================================================

void nes_screen_write_text(PPU* ppu, int row, int col, const char* text) {
    if (!ppu || !text || row < 0 || row >= NES_ROWS) return;

    uint16_t base = 0x2000 + static_cast<uint16_t>(row * NES_COLS + col);

    for (int i = 0; text[i] != '\0'; i++) {
        int c = col + i;
        if (c < 0) continue;
        if (c >= NES_COLS) break;

        uint8_t ch = static_cast<uint8_t>(text[i]);
        // Clamp to printable range
        if (ch < 0x20 || ch > 0x7F) ch = 0x20;

        ppu->ppu_write(base + i, ch);
    }
}

void nes_screen_write_text_n(PPU* ppu, int row, int col,
                              const char* text, int max_len) {
    if (!ppu || !text || row < 0 || row >= NES_ROWS) return;

    uint16_t base = 0x2000 + static_cast<uint16_t>(row * NES_COLS + col);

    for (int i = 0; i < max_len && text[i] != '\0'; i++) {
        int c = col + i;
        if (c < 0) continue;
        if (c >= NES_COLS) break;

        uint8_t ch = static_cast<uint8_t>(text[i]);
        if (ch < 0x20 || ch > 0x7F) ch = 0x20;

        ppu->ppu_write(base + i, ch);
    }
}

// ============================================================================
// ROW FILL
// ============================================================================

void nes_screen_fill_row(PPU* ppu, int row, uint8_t tile) {
    if (!ppu || row < 0 || row >= NES_ROWS) return;

    uint16_t base = 0x2000 + static_cast<uint16_t>(row * NES_COLS);
    for (int c = 0; c < NES_COLS; c++) {
        ppu->ppu_write(base + c, tile);
    }
}

// ============================================================================
// HEX / DECIMAL DISPLAY
// ============================================================================

static const char hex_chars[] = "0123456789ABCDEF";

void nes_screen_write_hex16(PPU* ppu, int row, int col, uint16_t value) {
    if (!ppu || row < 0 || row >= NES_ROWS) return;

    char buf[6] = { '$',
                    hex_chars[(value >> 12) & 0xF],
                    hex_chars[(value >> 8)  & 0xF],
                    hex_chars[(value >> 4)  & 0xF],
                    hex_chars[ value        & 0xF],
                    '\0' };
    nes_screen_write_text(ppu, row, col, buf);
}

void nes_screen_write_dec(PPU* ppu, int row, int col, int value) {
    if (!ppu || row < 0 || row >= NES_ROWS) return;

    char buf[8];
    snprintf(buf, sizeof(buf), "%d", value);
    nes_screen_write_text(ppu, row, col, buf);
}

// ============================================================================
// ATTRIBUTE TABLE
// ============================================================================

void nes_screen_set_attribute(PPU* ppu, int row, int col, uint8_t palette) {
    if (!ppu || row < 0 || row >= NES_ROWS || col < 0 || col >= NES_COLS) return;

    // Attribute table byte covers a 4×4 tile area (32×32 pixels).
    // Each byte has 4 2-bit palette selectors for the 4 quadrants.
    int attr_col = col / 4;
    int attr_row = row / 4;
    uint16_t attr_addr = 0x23C0 + static_cast<uint16_t>(attr_row * 8 + attr_col);

    // Which quadrant? (2×2 tiles within the 4×4 group)
    int quadrant = ((row / 2) & 1) * 2 + ((col / 2) & 1);
    int shift = quadrant * 2;

    uint8_t current = ppu->ppu_read(attr_addr);
    current &= ~(0x03 << shift);              // Clear old palette bits
    current |= (palette & 0x03) << shift;     // Set new palette bits
    ppu->ppu_write(attr_addr, current);
}

void nes_screen_set_row_attribute(PPU* ppu, int row, uint8_t palette) {
    if (!ppu || row < 0 || row >= NES_ROWS) return;

    for (int col = 0; col < NES_COLS; col += 2) {
        nes_screen_set_attribute(ppu, row, col, palette);
    }
}

// ============================================================================
// DISPLAY ENABLE
// ============================================================================

void nes_screen_enable_display(PPU* ppu) {
    if (!ppu) return;

    // Helper: construct a CPU-bus write cycle for a PPU register
    auto ppu_reg_write = [&](uint16_t addr, uint8_t data) {
        bus_state_t bus = NES_BUS_DEFAULT_STATE;
        BUS_SET_ADDR(bus, addr);
        BUS_SET_DATA(bus, data);
        BUS_CLR_BIT(bus, BUS_RW_BIT);  // write
        ppu->cpu_bus_tick(bus);
    };

    // PPUCTRL ($2000): NMI enable, pattern table 0 for background
    //   bit 7 = NMI enable (1)
    //   bit 4 = BG pattern table select (0 = $0000)
    //   bit 3 = Sprite pattern table select (0 = $0000)
    //   bit 2 = sprite size (0 = 8x8)
    //   bits 0-1 = nametable select (0 = $2000)
    ppu_reg_write(0x2000, 0x80);  // Enable NMI, use pattern table 0, nametable 0

    // PPUMASK ($2001): Enable background rendering
    //   bit 3 = show background (1)
    //   bit 1 = show background in leftmost 8px (1)
    ppu_reg_write(0x2001, 0x0A);  // Show background, no clipping

    // PPUSCROLL ($2005): No scrolling
    ppu_reg_write(0x2005, 0x00);  // X scroll = 0
    ppu_reg_write(0x2005, 0x00);  // Y scroll = 0
}

