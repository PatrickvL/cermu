// ---------- Pulldown algorithm ----------
// Generates base combined waveform table from physical model parameters.
// Algorithm from libsidplayfp/libresidfp by Antti Lankila & Leandro Nini.

static void generate_pulldown_table(const PulldownParams& p,
                                    const uint16_t* ci, // combined input (saw&tri, tri, or saw)
                                    uint16_t* out)
{
    // Precompute distance table: dt[12] = 1.0 (self), dt[12±i] = distance weight
    float dt[25];
    dt[12] = 1.0f;
    for (int i = 1; i <= 12; i++) {
        switch (p.dist_func) {
        case 0: // exponential
            dt[12 - i] = std::pow(p.distance1, static_cast<float>(-i));
            dt[12 + i] = std::pow(p.distance2, static_cast<float>(-i));
            break;
        case 1: // linear
            dt[12 - i] = 1.0f / (1.0f + i * p.distance1);
            dt[12 + i] = 1.0f / (1.0f + i * p.distance2);
            break;
        case 2: // quadratic
            dt[12 - i] = 1.0f / (1.0f + static_cast<float>(i * i) * p.distance1);
            dt[12 + i] = 1.0f / (1.0f + static_cast<float>(i * i) * p.distance2);
            break;
        }
    }

    // For each of the 4096 combined input values, compute pulled-down output
    for (int idx = 0; idx < 4096; idx++) {
        int input = ci[idx];

        // Extract 12 bits and scale bit 11 by topbit factor
        float bits[12];
        for (int b = 0; b < 12; b++)
            bits[b] = static_cast<float>((input >> b) & 1);
        bits[11] *= p.topbit;

        // For each bit position, compute pulldown from all other bits
        int result = 0;
        for (int sb = 0; sb < 12; sb++) {
            if (bits[sb] == 0.0f) continue; // bit not set, stays 0

            // Weighted sum of (1 - bit[cb]) for all other bits
            float pulldown = 0.0f;
            float norm = 0.0f;
            for (int cb = 0; cb < 12; cb++) {
                if (cb == sb) continue;
                float w = dt[sb - cb + 12];
                pulldown += (1.0f - bits[cb]) * w;
                norm += w;
            }

            pulldown = (pulldown - p.pulsestrength) / norm;
            float survival = 1.0f - pulldown;
            if (survival > p.threshold) {
                result |= (1 << sb);
            }
        }

        out[idx] = static_cast<uint16_t>(result) & 0xFFF0u;
    }
}

// Decode RLE delta and XOR with base table
static void apply_delta(const uint8_t* rle, uint16_t rle_size, uint16_t* table) {
    int pos = 0;
    for (uint16_t i = 0; i < rle_size; i += 2) {
        uint16_t val = static_cast<uint16_t>(rle[i]) << 4;
        uint8_t  cnt = rle[i + 1];
        for (uint8_t j = 0; j < cnt; j++) {
            table[pos] ^= val;
            pos++;
        }
    }
}

// ---------- Public interface ----------

uint16_t model_wave[2][8][4096] = {};

void init_waveform_tables() {
    static bool initialized = false;
    if (initialized) return;

    // Compute pure waveform tables (same for both chip models).
    uint16_t saw[4096];
    uint16_t tri[4096];
    uint32_t accumulator = 0;
    for (int i = 0; i < 4096; i++) {
        uint32_t msb = accumulator & 0x800000;

        // No waveform and pulse: 0xFFF mask (pulse handled via comparator).
        model_wave[0][0][i] = model_wave[1][0][i] = 0xfff;
        model_wave[0][4][i] = model_wave[1][4][i] = 0xfff;

        // Triangle: ((accumulator ^ -!!msb) >> 11) & 0xffe
        tri[i] = ((accumulator ^ (uint32_t)(-(int32_t)!!msb)) >> 11) & 0xffe;
        model_wave[0][1][i] = model_wave[1][1][i] = tri[i];

        // Sawtooth: accumulator >> 12
        saw[i] = accumulator >> 12;
        model_wave[0][2][i] = model_wave[1][2][i] = saw[i];

        accumulator += 0x1000;
    }

    // Precompute combined inputs for each waveform type
    // combo_to_wf: 0→ST(3), 1→PT(5), 2→PS(6), 3→PST(7)
    uint16_t ci[4][4096]; // combined input per combo type
    for (int i = 0; i < 4096; i++) {
        ci[0][i] = saw[i] & tri[i]; // ST
        ci[1][i] = tri[i];          // PT (pulse gates triangle)
        ci[2][i] = saw[i];          // PS (pulse gates sawtooth)
        ci[3][i] = saw[i] & tri[i]; // PST
    }

    // Generate combined waveform tables: algo base + XOR delta correction
    for (int model = 0; model < 2; model++) {
        for (int combo = 0; combo < 4; combo++) {
            int wf = combo_to_wf[combo];

            // Step 1: Generate base table from pulldown model
            generate_pulldown_table(pulldown_params[model][combo],
                                    ci[combo],
                                    model_wave[model][wf]);

            // Step 2: Apply RLE-encoded XOR delta corrections
            const auto& desc = combined_wf_delta[model][combo];
            apply_delta(desc.data, desc.size, model_wave[model][wf]);
        }
    }

    initialized = true;
}

