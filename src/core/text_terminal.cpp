// Fill remaining characters with block pattern
static uint8_t extended_font_8x8[256 * 8];
static bool font_initialized = false;

static void initialize_font() {
    if (font_initialized) return;
    
    // Copy base font
    memcpy(extended_font_8x8, default_font_8x8, sizeof(default_font_8x8));
    
    // Fill extended characters (0x80-0xFF) with block patterns
    for (int i = 128; i < 256; i++) {
        for (int j = 0; j < 8; j++) {
            extended_font_8x8[i * 8 + j] = 0xFF; // Solid block for now
        }
    }
    
    font_initialized = true;
}

