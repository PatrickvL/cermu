TextTerminal::TextTerminal(int cols, int rows, int char_width, int char_height)
    : cols_(cols)
    , rows_(rows)
    , char_width_(char_width)
    , char_height_(char_height)
    , cursor_col_(0)
    , cursor_row_(0)
    , cursor_visible_(true)
    , fg_color_(0xFF33FF33)  // Green (Apple 1 style)
    , bg_color_(0xFF000000)  // Black
    , font_data_(nullptr)
    , custom_font_(nullptr)
{
    // Allocate text buffer
    text_buffer_ = new char[cols_ * rows_];
    memset(text_buffer_, ' ', cols_ * rows_);
    
    // No per-character color buffers by default (use defaults)
    fg_color_buffer_ = nullptr;
    bg_color_buffer_ = nullptr;
    
    // Initialize font
    initialize_font();
    font_data_ = extended_font_8x8;
}

TextTerminal::~TextTerminal() {
    delete[] text_buffer_;
    delete[] custom_font_;
    if (fg_color_buffer_) delete[] fg_color_buffer_;
    if (bg_color_buffer_) delete[] bg_color_buffer_;
}

int TextTerminal::get_buffer_index(int col, int row) const {
    if (col < 0 || col >= cols_ || row < 0 || row >= rows_) {
        return -1;
    }
    return row * cols_ + col;
}

void TextTerminal::put_char(int col, int row, char ch) {
    int idx = get_buffer_index(col, row);
    if (idx >= 0) {
        text_buffer_[idx] = ch;
    }
}

void TextTerminal::put_char(int col, int row, char ch, uint32_t fg_color, uint32_t bg_color) {
    int idx = get_buffer_index(col, row);
    if (idx >= 0) {
        text_buffer_[idx] = ch;
        
        // Allocate color buffers if needed
        if (!fg_color_buffer_) {
            fg_color_buffer_ = new uint32_t[cols_ * rows_];
            for (int i = 0; i < cols_ * rows_; i++) {
                fg_color_buffer_[i] = fg_color_;
            }
        }
        if (!bg_color_buffer_) {
            bg_color_buffer_ = new uint32_t[cols_ * rows_];
            for (int i = 0; i < cols_ * rows_; i++) {
                bg_color_buffer_[i] = bg_color_;
            }
        }
        
        fg_color_buffer_[idx] = fg_color;
        bg_color_buffer_[idx] = bg_color;
    }
}

char TextTerminal::get_char(int col, int row) const {
    int idx = get_buffer_index(col, row);
    return (idx >= 0) ? text_buffer_[idx] : ' ';
}

void TextTerminal::clear() {
    memset(text_buffer_, ' ', cols_ * rows_);
}

void TextTerminal::clear(uint32_t bg_color) {
    clear();
    bg_color_ = bg_color;
    
    // Clear color buffers if they exist
    if (bg_color_buffer_) {
        for (int i = 0; i < cols_ * rows_; i++) {
            bg_color_buffer_[i] = bg_color;
        }
    }
}

void TextTerminal::scroll_up(int lines) {
    if (lines <= 0 || lines >= rows_) {
        clear();
        return;
    }
    
    // Move text up
    memmove(text_buffer_, text_buffer_ + (lines * cols_), 
            (rows_ - lines) * cols_);
    
    // Clear bottom lines
    memset(text_buffer_ + ((rows_ - lines) * cols_), ' ', lines * cols_);
    
    // Scroll color buffers if they exist
    if (fg_color_buffer_) {
        memmove(fg_color_buffer_, fg_color_buffer_ + (lines * cols_),
                (rows_ - lines) * cols_ * sizeof(uint32_t));
        for (int i = (rows_ - lines) * cols_; i < rows_ * cols_; i++) {
            fg_color_buffer_[i] = fg_color_;
        }
    }
    if (bg_color_buffer_) {
        memmove(bg_color_buffer_, bg_color_buffer_ + (lines * cols_),
                (rows_ - lines) * cols_ * sizeof(uint32_t));
        for (int i = (rows_ - lines) * cols_; i < rows_ * cols_; i++) {
            bg_color_buffer_[i] = bg_color_;
        }
    }
}

void TextTerminal::scroll_down(int lines) {
    if (lines <= 0 || lines >= rows_) {
        clear();
        return;
    }
    
    // Move text down
    memmove(text_buffer_ + (lines * cols_), text_buffer_,
            (rows_ - lines) * cols_);
    
    // Clear top lines
    memset(text_buffer_, ' ', lines * cols_);
    
    // Scroll color buffers if they exist
    if (fg_color_buffer_) {
        memmove(fg_color_buffer_ + (lines * cols_), fg_color_buffer_,
                (rows_ - lines) * cols_ * sizeof(uint32_t));
        for (int i = 0; i < lines * cols_; i++) {
            fg_color_buffer_[i] = fg_color_;
        }
    }
    if (bg_color_buffer_) {
        memmove(bg_color_buffer_ + (lines * cols_), bg_color_buffer_,
                (rows_ - lines) * cols_ * sizeof(uint32_t));
        for (int i = 0; i < lines * cols_; i++) {
            bg_color_buffer_[i] = bg_color_;
        }
    }
}

void TextTerminal::set_cursor(int col, int row) {
    cursor_col_ = std::max(0, std::min(col, cols_ - 1));
    cursor_row_ = std::max(0, std::min(row, rows_ - 1));
}

void TextTerminal::get_cursor(int* col, int* row) const {
    if (col) *col = cursor_col_;
    if (row) *row = cursor_row_;
}

void TextTerminal::show_cursor(bool show) {
    cursor_visible_ = show;
}

void TextTerminal::set_foreground_color(uint32_t color) {
    fg_color_ = color;
}

void TextTerminal::set_background_color(uint32_t color) {
    bg_color_ = color;
}

const uint8_t* TextTerminal::get_default_font() {
    initialize_font();
    return extended_font_8x8;
}

void TextTerminal::set_font(const uint8_t* font_data) {
    static constexpr size_t FONT_SIZE = 256 * 8;
    if (!custom_font_) {
        custom_font_ = new uint8_t[FONT_SIZE];
    }
    memcpy(custom_font_, font_data, FONT_SIZE);
    font_data_ = custom_font_;
}

void TextTerminal::render_char(uint32_t* framebuffer, int fb_width, int x, int y,
                               char ch, uint32_t fg, uint32_t bg) {
    if (!font_data_) return;
    
    uint8_t char_index = static_cast<uint8_t>(ch);
    const uint8_t* glyph = &font_data_[char_index * 8];
    
    for (int py = 0; py < char_height_ && (y + py) < fb_width; py++) {
        uint8_t row_data = glyph[py];
        for (int px = 0; px < char_width_ && (x + px) < fb_width; px++) {
            bool pixel_on = (row_data & (0x80 >> px)) != 0;
            int fb_idx = (y + py) * fb_width + (x + px);
            framebuffer[fb_idx] = pixel_on ? fg : bg;
        }
    }
}

void TextTerminal::render(uint32_t* framebuffer, int fb_width, int fb_height) {
    if (!framebuffer) return;
    
    // Clear framebuffer to background color
    for (int i = 0; i < fb_width * fb_height; i++) {
        framebuffer[i] = bg_color_;
    }
    
    // Render each character
    for (int row = 0; row < rows_; row++) {
        for (int col = 0; col < cols_; col++) {
            int idx = get_buffer_index(col, row);
            if (idx < 0) continue;
            
            char ch = text_buffer_[idx];
            uint32_t fg = fg_color_buffer_ ? fg_color_buffer_[idx] : fg_color_;
            uint32_t bg = bg_color_buffer_ ? bg_color_buffer_[idx] : bg_color_;
            
            int x = col * char_width_;
            int y = row * char_height_;
            
            render_char(framebuffer, fb_width, x, y, ch, fg, bg);
            
            // Render cursor if at this position
            if (cursor_visible_ && col == cursor_col_ && row == cursor_row_) {
                // Draw cursor as inverted colors on bottom line of character
                int cursor_y = y + char_height_ - 1;
                if (cursor_y < fb_height) {
                    for (int px = 0; px < char_width_ && (x + px) < fb_width; px++) {
                        framebuffer[cursor_y * fb_width + x + px] = fg;
                    }
                }
            }
        }
    }
}